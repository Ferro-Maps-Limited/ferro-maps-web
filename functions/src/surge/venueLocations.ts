/* Normalise a sheet ground name for table lookup. */
export function normVenueName(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim().replace(/\s+/g, " ");
}

const INDEX: Map<string, VenueLocation> = (() => {
  const map = new Map<string, VenueLocation>();
  for (const venue of VENUE_LOCATIONS) {
    for (const label of [venue.name, ...venue.aliases]) {
      const key = normVenueName(label);
      if (key && !map.has(key)) map.set(key, venue);
    }
  }
  return map;
})();

export function lookupVenueLocation(ground: string): VenueLocation | null {
  const key = normVenueName(ground);
  if (!key) return null;
  return INDEX.get(key) ?? null;
}

